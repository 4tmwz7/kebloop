import AppKit
import XCTest
@testable import Kebloop

@MainActor
final class ClipboardHistoryTests: XCTestCase {
    func testPreexistingClipboardIsNotCollected() async throws {
        let fixture = try makeFixture(initialClipboard: "copied before launch")
        defer { fixture.cleanup() }
        fixture.store.poll()
        XCTAssertTrue(fixture.store.items.isEmpty)
        fixture.write("new copy")
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.map(\.text), ["new copy"])
        await settleStorage()
    }

    func testDuplicateMovesToFrontAndRetainsIdentity() async throws {
        let fixture = try makeFixture()
        defer { fixture.cleanup() }
        fixture.write("first")
        fixture.store.poll()
        let originalID = try XCTUnwrap(fixture.store.items.first?.id)
        fixture.write("second")
        fixture.store.poll()
        fixture.write("first")
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.map(\.text), ["first", "second"])
        XCTAssertEqual(fixture.store.items.first?.id, originalID)
        await settleStorage()
    }

    func testDisabledGapDoesNotIngestClipboardWhenReenabled() async throws {
        let fixture = try makeFixture()
        defer { fixture.cleanup() }
        fixture.write("keep this")
        fixture.store.poll()
        fixture.store.enabled = false
        fixture.write("ignore while disabled")
        fixture.store.enabled = true
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.map(\.text), ["keep this"])
        fixture.write("record after enabling")
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.map(\.text), ["record after enabling", "keep this"])
        await settleStorage()
    }

    func testSensitivePasteboardMarkersPreventRecording() async throws {
        let fixture = try makeFixture()
        defer { fixture.cleanup() }
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            fixture.write("synthetic sensitive text")
            fixture.pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
            fixture.store.poll()
            XCTAssertTrue(fixture.store.items.isEmpty, "Marker \(marker) should suppress collection")
        }
        fixture.write("normal text")
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.map(\.text), ["normal text"])
        await settleStorage()
    }

    func testClearPreventsPendingLoadFromRestoringHistory() async throws {
        let saved = ClipboardEntry(id: "saved", text: "old synthetic text", date: Date())
        let fixture = try makeFixture(initialEntries: [saved])
        defer { fixture.cleanup() }
        // No actor suspension here: the asynchronous load cannot publish before clear.
        fixture.store.clear()
        await settleStorage()
        XCTAssertTrue(fixture.store.items.isEmpty)
        let savedItems = try JSONDecoder().decode([ClipboardEntry].self, from: Data(contentsOf: fixture.storageURL))
        XCTAssertTrue(savedItems.isEmpty)
    }

    func testSizeLimitUsesUTF8BytesAndHistoryIsCapped() async throws {
        let fixture = try makeFixture()
        defer { fixture.cleanup() }
        fixture.write(String(repeating: "a", count: 100 * 1024))
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.count, 1)
        fixture.write(String(repeating: "a", count: 100 * 1024 + 1))
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.count, 1)
        // A character count alone would incorrectly admit this multibyte string.
        fixture.write(String(repeating: "😀", count: 30_000))
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.count, 1)
        for index in 0..<205 {
            fixture.write("synthetic entry \(index)")
            fixture.store.poll()
        }
        XCTAssertEqual(fixture.store.items.count, 200)
        XCTAssertEqual(fixture.store.items.first?.text, "synthetic entry 204")
        XCTAssertEqual(fixture.store.items.last?.text, "synthetic entry 5")
        // This case queues many writes; wait until the final snapshot is present.
        for _ in 0..<100 {
            let persisted = (try? Data(contentsOf: fixture.storageURL))
                .flatMap { try? JSONDecoder().decode([ClipboardEntry].self, from: $0) }
            if persisted?.first?.text == "synthetic entry 204", persisted?.count == 200 { break }
            try await Task.sleep(for: .milliseconds(20))
        }
        await settleStorage()
        let persisted = try JSONDecoder().decode([ClipboardEntry].self, from: Data(contentsOf: fixture.storageURL))
        XCTAssertEqual(persisted.count, 200)
        XCTAssertEqual(persisted.first?.text, "synthetic entry 204")
    }

    func testRemovePersistsWithoutDeletingOtherEntriesOrRecollectingClipboard() async throws {
        let fixture = try makeFixture()
        defer { fixture.cleanup() }
        fixture.write("keep")
        fixture.store.poll()
        fixture.write("remove")
        fixture.store.poll()
        let removedID = try XCTUnwrap(fixture.store.items.first?.id)
        fixture.store.remove(id: removedID)
        fixture.store.poll()
        XCTAssertEqual(fixture.store.items.map(\.text), ["keep"])
        await settleStorage()
        let saved = try JSONDecoder().decode([ClipboardEntry].self, from: Data(contentsOf: fixture.storageURL))
        XCTAssertEqual(saved.map(\.text), ["keep"])
        fixture.store.clear()
        fixture.store.poll()
        await settleStorage()
        XCTAssertTrue(fixture.store.items.isEmpty)
        let cleared = try JSONDecoder().decode([ClipboardEntry].self, from: Data(contentsOf: fixture.storageURL))
        XCTAssertTrue(cleared.isEmpty)
    }

    func testSnapshotWriterCoalescesBurstToLatestSnapshot() async throws {
        let firstWriteStarted = DispatchSemaphore(value: 0)
        let finishFirstWrite = DispatchSemaphore(value: 0)
        let recorder = SnapshotRecorder()
        let writer = CoalescedSnapshotWriter<Int>(queue: DispatchQueue(label: "ClipboardHistoryTests.snapshot-writer")) { value in
            if value == 0 {
                firstWriteStarted.signal()
                finishFirstWrite.wait()
            }
            recorder.append(value)
        }

        writer.enqueue(0)
        XCTAssertEqual(firstWriteStarted.wait(timeout: .now() + 2), .success)
        for snapshot in 1...500 { writer.enqueue(snapshot) }
        finishFirstWrite.signal()

        for _ in 0..<100 where recorder.values.last != 500 {
            try await Task.sleep(for: .milliseconds(10))
        }
        XCTAssertEqual(recorder.values, [0, 500], "A burst should write the in-flight snapshot and only its newest successor")
    }

    func testFileSearchStopCancelsPendingDebounce() async throws {
        let service = FileSearchService()
        service.search("synthetic-unlikely-filename")
        XCTAssertTrue(service.isSearching)
        service.stop()
        try await Task.sleep(for: .milliseconds(250))
        XCTAssertFalse(service.isSearching)
        XCTAssertTrue(service.results.isEmpty)
        service.search("   ")
        XCTAssertFalse(service.isSearching)
    }

    private func settleStorage() async {
        try? await Task.sleep(for: .milliseconds(150))
    }

    private func makeFixture(initialClipboard: String? = nil, initialEntries: [ClipboardEntry]? = nil) throws -> Fixture {
        let suite = "KebloopTests.\(UUID().uuidString)"
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        defaults.set(true, forKey: "clipboardHistoryEnabled")
        let pasteboard = NSPasteboard(name: NSPasteboard.Name(suite))
        if let initialClipboard { pasteboard.setString(initialClipboard, forType: .string) }
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(suite, isDirectory: true)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let storageURL = directory.appendingPathComponent("history.json")
        if let initialEntries { try JSONEncoder().encode(initialEntries).write(to: storageURL) }
        let store = ClipboardHistoryStore(defaults: defaults, pasteboard: pasteboard, storageURL: storageURL)
        return Fixture(store: store, pasteboard: pasteboard, defaults: defaults, suite: suite,
                       directory: directory, storageURL: storageURL)
    }
}

private final class SnapshotRecorder: @unchecked Sendable {
    private let lock = NSLock()
    private var recordedValues: [Int] = []

    var values: [Int] {
        lock.lock()
        defer { lock.unlock() }
        return recordedValues
    }

    func append(_ value: Int) {
        lock.lock()
        recordedValues.append(value)
        lock.unlock()
    }
}

@MainActor
private struct Fixture {
    let store: ClipboardHistoryStore
    let pasteboard: NSPasteboard
    let defaults: UserDefaults
    let suite: String
    let directory: URL
    let storageURL: URL

    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    func cleanup() {
        pasteboard.releaseGlobally()
        defaults.removePersistentDomain(forName: suite)
        try? FileManager.default.removeItem(at: directory)
    }
}
